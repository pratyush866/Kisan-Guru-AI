export class TranslationUtils {
  /**
   * Translates a dictionary key based on active language set in context.
   */
  static translate(key, language = 'english') {
    const lang = language.toLowerCase();
    const dict = DICTIONARY[lang] || DICTIONARY['english'];
    return dict[key] || DICTIONARY['english'][key] || key;
  }
}
