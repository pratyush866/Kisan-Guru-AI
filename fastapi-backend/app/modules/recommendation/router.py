import json
from fastapi import APIRouter, Depends, HTTPException, status, Query
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select
from sqlalchemy import func
from typing import List
from datetime import datetime, timezone
import uuid

from app.core.database import get_db_session
from app.core.models import User, RecommendationHistory
from app.modules.auth.router import get_current_user
from app.modules.schemas import (
  RecommendationInput,
  RecommendationResponse,
  RecommendationHistoryOut,
  RecommendationFavoriteIn
)
from app.modules.recommendation.service import CropRecommendationService

router = APIRouter(prefix="/recommendations", tags=["Smart Crop Recommendation Engine"])

@router.post("", response_model=RecommendationResponse, status_code=status.HTTP_201_CREATED)
async def generate_crop_recommendation(
  input_data: RecommendationInput,
  current_user: User = Depends(get_current_user),
  db: AsyncSession = Depends(get_db_session)
):
  """
  Submits a set of soil, weather, economic, and regional parameters to evaluate,
  returns the ranked top 3 crop matches, and logs the request to the farmer's history ledger.
  """
  try:
    # 1. Run the recommendation matching calculation
    ranked_crops = CropRecommendationService.calculate_recommendations(input_data)
    
    # 2. Serialize inputs and results to JSON strings for database archival
    # Convert Pydantic model to dict
    inputs_dict = input_data.model_dump()
    results_list = [crop.model_dump() for crop in ranked_crops]
    
    inputs_str = json.dumps(inputs_dict)
    results_str = json.dumps(results_list)
    
    # 3. Save to database history
    new_record = RecommendationHistory(
      user_id=current_user.id,
      inputs_json=inputs_str,
      results_json=results_str,
      is_favorite=False
    )
    if not new_record.id:
      new_record.id = str(uuid.uuid4())
    if not new_record.created_at:
      new_record.created_at = datetime.now(timezone.utc)
    
    db.add(new_record)
    await db.flush()
    
    # Map model to response schema
    return RecommendationResponse(
      id=new_record.id,
      recommendations=ranked_crops,
      created_at=new_record.created_at
    )
  except Exception as e:
    raise HTTPException(
      status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
      detail=f"An error occurred while generating recommendations: {str(e)}"
    )

@router.get("/history", response_model=List[RecommendationHistoryOut])
async def get_recommendation_history(
  current_user: User = Depends(get_current_user),
  db: AsyncSession = Depends(get_db_session)
):
  """
  Retrieves the history of crop recommendation sheets generated by the current farmer, sorted chronologically.
  """
  result = await db.execute(
    select(RecommendationHistory)
    .filter(RecommendationHistory.user_id == current_user.id)
    .order_by(RecommendationHistory.created_at.desc())
  )
  records = result.scalars().all()
  
  history_out = []
  for rec in records:
    history_out.append(
      RecommendationHistoryOut(
        id=rec.id,
        inputs=json.loads(rec.inputs_json),
        results=json.loads(rec.results_json),
        is_favorite=rec.is_favorite,
        created_at=rec.created_at
      )
    )
  return history_out

@router.get("/analytics")
async def get_recommendation_analytics(
  current_user: User = Depends(get_current_user),
  db: AsyncSession = Depends(get_db_session)
):
  """
  Aggregates the user's historical queries to produce summary dashboard cards.
  """
  # Fetch user's query history
  result = await db.execute(
    select(RecommendationHistory)
    .filter(RecommendationHistory.user_id == current_user.id)
  )
  records = result.scalars().all()
  
  if not records:
    return {
      "total_queries": 0,
      "avg_ph": 0.0,
      "avg_nitrogen": 0.0,
      "avg_phosphorus": 0.0,
      "avg_potassium": 0.0,
      "most_recommended_crop": "None",
      "favorite_count": 0
    }
  
  total_queries = len(records)
  favorite_count = sum(1 for r in records if r.is_favorite)
  
  sum_ph = 0.0
  sum_n = 0.0
  sum_p = 0.0
  sum_k = 0.0
  crop_counts = {}
  
  for rec in records:
    inputs = json.loads(rec.inputs_json)
    results = json.loads(rec.results_json)
    
    sum_ph += inputs.get("pH", 0.0)
    sum_n += inputs.get("N", 0.0)
    sum_p += inputs.get("P", 0.0)
    sum_k += inputs.get("K", 0.0)
    
    if results and len(results) > 0:
      top_crop = results[0].get("crop_name", "Unknown")
      crop_counts[top_crop] = crop_counts.get(top_crop, 0) + 1
      
  most_recommended = max(crop_counts, key=crop_counts.get) if crop_counts else "None"
  
  return {
    "total_queries": total_queries,
    "avg_ph": round(sum_ph / total_queries, 2),
    "avg_nitrogen": round(sum_n / total_queries, 1),
    "avg_phosphorus": round(sum_p / total_queries, 1),
    "avg_potassium": round(sum_k / total_queries, 1),
    "most_recommended_crop": most_recommended,
    "favorite_count": favorite_count
  }

@router.get("/{rec_id}", response_model=RecommendationHistoryOut)
async def get_single_recommendation(
  rec_id: str,
  current_user: User = Depends(get_current_user),
  db: AsyncSession = Depends(get_db_session)
):
  """
  Retrieves a specific recommendation card by its primary key UUID.
  """
  result = await db.execute(
    select(RecommendationHistory)
    .filter(RecommendationHistory.id == rec_id, RecommendationHistory.user_id == current_user.id)
  )
  rec = result.scalars().first()
  if not rec:
    raise HTTPException(
      status_code=status.HTTP_404_NOT_FOUND,
      detail="Crop recommendation report not found."
    )
    
  return RecommendationHistoryOut(
    id=rec.id,
    inputs=json.loads(rec.inputs_json),
    results=json.loads(rec.results_json),
    is_favorite=rec.is_favorite,
    created_at=rec.created_at
  )

@router.post("/{rec_id}/favorite", response_model=RecommendationHistoryOut)
async def toggle_favorite_recommendation(
  rec_id: str,
  fav_in: RecommendationFavoriteIn,
  current_user: User = Depends(get_current_user),
  db: AsyncSession = Depends(get_db_session)
):
  """
  Favorites or unsaves a recommendation record in the user history ledgers.
  """
  result = await db.execute(
    select(RecommendationHistory)
    .filter(RecommendationHistory.id == rec_id, RecommendationHistory.user_id == current_user.id)
  )
  rec = result.scalars().first()
  if not rec:
    raise HTTPException(
      status_code=status.HTTP_404_NOT_FOUND,
      detail="Crop recommendation report not found."
    )
    
  rec.is_favorite = fav_in.is_favorite
  await db.flush()
  
  return RecommendationHistoryOut(
    id=rec.id,
    inputs=json.loads(rec.inputs_json),
    results=json.loads(rec.results_json),
    is_favorite=rec.is_favorite,
    created_at=rec.created_at
  )
